import * as React from "react"
import { cn } from "@/lib/utils"

export interface ButtonProps
  extends React.ButtonHTMLAttributes<HTMLButtonElement> {
  variant?: "default" | "outline" | "ghost" | "link" | "glass"
  size?: "default" | "sm" | "lg" | "icon"
}

const Button = React.forwardRef<HTMLButtonElement, ButtonProps>(
  ({ className, variant = "default", size = "default", ...props }, ref) => {
    return (
      <button
        ref={ref}
        className={cn(
          "inline-flex items-center justify-center whitespace-nowrap rounded-md text-sm font-medium ring-offset-background transition-colors focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring focus-visible:ring-offset-2 disabled:pointer-events-none disabled:opacity-50",
          {
            "bg-ocean-blue text-white hover:bg-ocean-blue/90 shadow-lg shadow-ocean-blue/20": variant === "default",
            "border border-ocean-blue text-ocean-blue hover:bg-ocean-blue/10": variant === "outline",
            "hover:bg-ocean-blue/10 hover:text-ocean-blue text-foreground": variant === "ghost",
            "text-ocean-cyan underline-offset-4 hover:underline": variant === "link",
            "glass-panel text-ocean-cyan hover:bg-ocean-cyan/10": variant === "glass",
            "h-10 px-4 py-2": size === "default",
            "h-9 rounded-md px-3": size === "sm",
            "h-11 rounded-md px-8": size === "lg",
            "h-10 w-10": size === "icon",
          },
          className
        )}
        {...props}
      />
    )
  }
)
Button.displayName = "Button"

export { Button }
